"""Backend SSH to a work node: durable credentials and verified server identity.

Every new work node gets two keypairs generated by the backend before the provider launch call:

- a **sync key**, whose public half is authorized for the ``bioaf-sync`` account and whose private
  half is stored encrypted on the node's session row, so any worker can save outputs after a
  restart;
- a **host key**, which the node installs as its only SSH server key and whose public half is
  recorded on the session row, so the backend connects only to the server it launched.

The host private key reaches the node through provider startup metadata / user data. That is not a
secret store: authorized cloud readers and guest processes able to query metadata can read it. The
tradeoff is recorded in the engineering plan; nothing here logs key material.

No first-use trust, network key scan or ``known_hosts=None`` is used. A missing credential or a
different server key refuses before any remote command runs.
"""

from __future__ import annotations

import asyncio
from dataclasses import dataclass

import asyncssh

HOST_KEY_PATH = "/etc/ssh/bioaf_host_ed25519_key"
HOST_KEY_CONFIG = "/etc/ssh/sshd_config.d/00-bioaf-host-key.conf"
SYNC_USER = "bioaf-sync"

# The readiness version of a session row whose sync key and host identity are durable. Sessions
# without it (launched before this release) hold their sync key only in an old process's memory.
NODE_TRUST_VERSION = 1


# Why a Stop kept the node (TerminationResult.stop_failure / ComputeSession.stop_failure).
STOP_SAVE_FAILED = "save_failed"
STOP_DELETE_UNCONFIRMED = "delete_unconfirmed"
STOP_STATE_UNKNOWN = "state_unknown"


def sync_outputs_command(
    sync_outputs: str, capture_each: str, *, home: str = "/home", outputs: str = "/outputs"
) -> str:
    """The node-side save: output directory sync plus notebook/script capture.

    Exits nonzero if the output sync or any copy of a found script fails, so a successful later
    command cannot mask a failed earlier one. An empty /outputs is a checked, successful no-op.
    Directories bioaf-sync cannot read (other accounts' homes, ~/.ssh) are skipped, not failures:
    find's own errors are dropped and only the copies' exit status (through xargs) counts.
    """
    return (
        "rc=0; "
        f'if [ -d {outputs} ] && [ -n "$(ls -A {outputs})" ]; then {sync_outputs} || rc=1; fi; '
        f"find {home} -maxdepth 4 "
        r"\( -name '*.ipynb' -o -name '*.Rmd' -o -name '*.R' -o -name '*.py' \) "
        f"-type f -print0 2>/dev/null | xargs -0 sh -c {capture_each} sh || rc=1; "
        "exit $rc"
    )


class NodeSyncError(Exception):
    """The backend could not complete a command on the node (unreachable, timeout, refused)."""


class NodeTrustError(NodeSyncError):
    """The node's identity or the backend's credentials could not be verified. No command ran."""


@dataclass(frozen=True)
class NodeIdentity:
    sync_private_key: str
    sync_public_key: str
    host_private_key: str
    host_public_key: str


def generate_node_identity() -> NodeIdentity:
    """Fresh, independent sync and host keypairs for one launch attempt."""
    sync = asyncssh.generate_private_key("ssh-ed25519")
    host = asyncssh.generate_private_key("ssh-ed25519")
    return NodeIdentity(
        sync_private_key=sync.export_private_key().decode(),
        sync_public_key=sync.export_public_key().decode().strip(),
        host_private_key=host.export_private_key().decode(),
        host_public_key=host.export_public_key().decode().strip(),
    )


def host_key_install_lines(host_private_key: str, host_public_key: str) -> list[str]:
    """Startup-script lines that make the launch host key the node's only SSH server key.

    The image's own host keys are shared by every node built from it, so they are removed. The
    script is rerun on every boot of the same instance (GCE) and writes the same key, so a reboot
    keeps the identity; a replacement instance gets a new key from its own launch.
    """
    public = host_public_key.strip().replace("'", "")
    return [
        "",
        "# 0. Server identity recorded by bioAF at launch",
        "rm -f /etc/ssh/ssh_host_*",
        "(umask 077 && cat > " + HOST_KEY_PATH + " <<'BIOAF_HOST_KEY_EOF'",
        host_private_key.strip(),
        "BIOAF_HOST_KEY_EOF",
        ")",
        f"printf '%s\\n' '{public}' > {HOST_KEY_PATH}.pub",
        f"chown root:root {HOST_KEY_PATH} {HOST_KEY_PATH}.pub",
        f"chmod 600 {HOST_KEY_PATH}",
        f"chmod 644 {HOST_KEY_PATH}.pub",
        f"printf 'HostKey {HOST_KEY_PATH}\\n' > {HOST_KEY_CONFIG}",
        "if /usr/sbin/sshd -t; then",
        "  systemctl reload ssh 2>/dev/null || systemctl reload sshd 2>/dev/null"
        " || systemctl restart ssh 2>/dev/null || systemctl restart sshd 2>/dev/null || true",
        "else",
        "  echo 'bioAF: sshd configuration failed validation; host identity not applied' >&2",
        "fi",
    ]


async def run_sync_command(
    address: str,
    *,
    sync_private_key: str | None,
    host_public_key: str | None,
    command: str,
    port: int = 22,
    timeout: float = 300,
) -> int:
    """Run ``command`` as ``bioaf-sync`` on a node whose host key is ``host_public_key``.

    Returns the command's exit status. Raises NodeTrustError when a credential is missing or
    unusable or the server presents any other key; NodeSyncError when the node cannot be reached
    or the command does not finish in time.
    """
    if not sync_private_key or not host_public_key:
        raise NodeTrustError("missing durable sync credential or recorded host identity")
    try:
        client_key = asyncssh.import_private_key(sync_private_key)
        trusted_host = asyncssh.import_public_key(host_public_key)
    except (asyncssh.KeyImportError, ValueError) as exc:
        raise NodeTrustError("stored node credential could not be read") from exc

    try:
        async with asyncssh.connect(
            address,
            port=port,
            username=SYNC_USER,
            client_keys=[client_key],
            known_hosts=([trusted_host], [], []),
            agent_path=None,
            config=None,
            password=None,
            kbdint_auth=False,
            connect_timeout=min(timeout, 30),
        ) as conn:
            result = await asyncio.wait_for(conn.run(command), timeout=timeout)
    except asyncssh.HostKeyNotVerifiable as exc:
        raise NodeTrustError("node presented an unrecognized server key") from exc
    except asyncssh.PermissionDenied as exc:
        raise NodeTrustError("node refused the backend sync credential") from exc
    except (OSError, asyncio.TimeoutError, asyncssh.Error) as exc:
        raise NodeSyncError(type(exc).__name__) from exc
    return result.exit_status if result.exit_status is not None else 255
