#!/bin/sh
set -e

# ---------------------------------------------------------------------------
# Bootstrap BIOAF_ENCRYPTION_KEYS if missing.
#
# Background: v0.13.0 introduced at-rest column encryption gated on the
# BIOAF_ENCRYPTION_KEYS env var. On a fresh install or a v0.13.x->v0.13.y
# upgrade, the host-side ./install.sh ensure-encryption-key step seeds the
# key into docker/.env before the backend container starts. But for
# upgrades FROM any version < 0.13.0, the running bioaf script's
# cmd_update was parsed into memory before the git checkout brought in
# v0.13.0's version, so the ensure-encryption-key step never executes.
# The backend container would then refuse to start, breaking the upgrade
# for non-technical operators (no SSH-in remediation is acceptable).
#
# The fix has to live in something that IS read fresh from disk during
# that upgrade. docker-compose.yml is re-read on every `$DC up -d`, and
# the backend image is re-pulled. So the v0.13.1 docker-compose.yml
# mounts the host's docker/.env at /host/.env (writable), and this
# entrypoint writes the new key to that mount so subsequent compose
# invocations pass it through as the env var.
#
# Skipped (no-op) when:
#   - BIOAF_ENCRYPTION_KEYS is already set (fresh installs, normal upgrades,
#     or a container started with the value supplied externally).
#
# Fails loudly when:
#   - The variable is empty AND /host/.env is not mounted (a container started
#     outside the Compose stack must be given the value by its caller).
#   - The variable is empty AND /host/.env is present but not writable
#     (the upgrade would be silently incomplete otherwise; better to fail).
# ---------------------------------------------------------------------------

bootstrap_encryption_key() {
    if [ -n "${BIOAF_ENCRYPTION_KEYS:-}" ]; then
        return 0
    fi

    if [ ! -e /host/.env ]; then
        # No host env file mounted: the container was started outside the
        # Compose stack, so BIOAF_ENCRYPTION_KEYS must be supplied by whoever
        # started it. Generating a key here would not persist. Fail clearly.
        echo "FATAL: BIOAF_ENCRYPTION_KEYS is unset and no host .env is mounted." >&2
        echo "  Outside docker/docker-compose.yml, supply BIOAF_ENCRYPTION_KEYS yourself." >&2
        echo "  See decisions/ADR-047-data-at-rest-encryption.md." >&2
        return 1
    fi

    if [ ! -w /host/.env ]; then
        echo "FATAL: BIOAF_ENCRYPTION_KEYS is unset and /host/.env is read-only." >&2
        echo "  The container cannot auto-generate a persistent key. This will" >&2
        echo "  break the upgrade. Make docker/.env writable by the container" >&2
        echo "  user, or set BIOAF_ENCRYPTION_KEYS yourself, then restart." >&2
        return 1
    fi

    # Idempotency guard: if .env already has a non-empty BIOAF_ENCRYPTION_KEYS
    # line, the env var should have been populated by compose. If it wasn't,
    # something went wrong with env-file expansion. Refuse to overwrite a
    # value that might be encrypting existing data.
    existing_line=$(grep -E "^BIOAF_ENCRYPTION_KEYS=" /host/.env 2>/dev/null | tail -1 || true)
    existing_value=${existing_line#BIOAF_ENCRYPTION_KEYS=}
    if [ -n "$existing_value" ]; then
        echo "WARNING: BIOAF_ENCRYPTION_KEYS env var is empty but /host/.env has a value." >&2
        echo "  Refusing to overwrite. Investigate the env-file plumbing." >&2
        export BIOAF_ENCRYPTION_KEYS="$existing_value"
        return 0
    fi

    # Generate a Fernet key inside the container. python3 + cryptography are
    # already in this image (cryptography is a hard requirement of the
    # backend), so no additional dependency is introduced.
    new_key=$(python -c "from cryptography.fernet import Fernet; print(Fernet.generate_key().decode())")
    if [ -z "$new_key" ] || [ "${#new_key}" -ne 44 ]; then
        echo "FATAL: Failed to generate a Fernet key inside the container." >&2
        return 1
    fi

    # Append rather than sed-in-place: bind-mounted single files lose their
    # inode binding under atomic-rename writes, so the container's view of
    # /host/.env would orphan. compose's env-file parser uses last-occurrence-
    # wins for duplicate keys, so appending is safe even if a blank
    # BIOAF_ENCRYPTION_KEYS= line happens to exist further up the file.
    {
        printf '\n'
        printf '# Auto-generated by the backend container on %s.\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
        printf '# This typically only happens on upgrades from < 0.13.0 where the\n'
        printf '# host-side ensure-encryption-key step could not run.\n'
        printf '# LOSING THIS VALUE LOSES THE DATA -- back it up alongside the DB dump.\n'
        printf 'BIOAF_ENCRYPTION_KEYS=%s\n' "$new_key"
    } >> /host/.env

    echo "INFO: BIOAF_ENCRYPTION_KEYS was missing; auto-generated a new Fernet key"
    echo "INFO: and persisted it to docker/.env on the host. Future container"
    echo "INFO: restarts will pick it up via compose env-file expansion."
    echo "INFO: Operator action: back up this key value separately from the DB dump."

    export BIOAF_ENCRYPTION_KEYS="$new_key"
}

# ---------------------------------------------------------------------------
# Upgrade the database before the application serves (plan 9).
#
# Runs on every start of the application server, so the first start of a new
# image upgrades the database whichever updater started it: this file and
# docker-compose.yml are read fresh on every update, the host's ./bioaf may not
# be. backend/app/schema_upgrade.py does the work (lock, verified recovery
# backup in /app/backups, migrate, validate, record). If it fails, the server
# still starts, but in maintenance: it answers 503 with the reason and does no
# normal work until `./bioaf migrate` (or the next update) completes the
# upgrade. There is no switch to skip this: the application's own gate would
# refuse normal service anyway. One-off commands (`docker compose run backend
# <cmd>`) are left alone.
# ---------------------------------------------------------------------------

run_database_upgrade() {
    [ "${1:-}" = "uvicorn" ] || return 0

    # Docker creates a missing bind-mount source as root; give it to the owner
    # of the host's .env (the operator) so ./bioaf backup can write there too.
    if [ -d "${BIOAF_UPGRADE_BACKUPS_DIR:-/app/backups}" ] && [ -e /host/.env ]; then
        chown "$(stat -c %u:%g /host/.env)" "${BIOAF_UPGRADE_BACKUPS_DIR:-/app/backups}" 2>/dev/null || true
    fi

    echo "Upgrading the database..."
    if python -m app.schema_upgrade run; then
        return 0
    fi
    echo "WARNING: the database upgrade did not complete; serving maintenance responses only." >&2
    echo "  Details: /app/update-status/schema-upgrade.json (update-status/ on the host)." >&2
    echo "  Fix the cause, then run: ./bioaf migrate" >&2
    return 0
}

bootstrap_encryption_key
run_database_upgrade "$@"

exec "$@"
